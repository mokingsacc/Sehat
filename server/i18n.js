export const pickLang = (x) => (LANGS.includes(x) ? x : 'en');
export function t(lang, key, vars) {
  const w = W[key];
  let s = w ? w[IDX[lang] || 0] || w[0] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}
